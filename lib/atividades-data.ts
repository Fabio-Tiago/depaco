export function getAtividadesPorTipo(tipo: string) {
  return ATIVIDADES.filter((a) => a.tipo === tipo);
}

export const TIPOS = Array.from(new Set(ATIVIDADES.map((a) => a.tipo))).map((tipo) => {
  const primeira = ATIVIDADES.find((a) => a.tipo === tipo)!;
  return { tipo, nome: primeira.tipo_nome, total: getAtividadesPorTipo(tipo).length };
});
